"""Run the development-only Evaluation v2 on the published 2025 cohort."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pharmaopt_metrics import (
    DEFAULT_BOOTSTRAP_SEED,
    DEFAULT_REVIEW_BUDGETS,
    cluster_bootstrap_ranking,
    compare_rankings,
    derive_product_ndc,
    evaluate_product_ranking,
    seeded_random_review,
)


DATA_PATH = ROOT / "pharmaopt_2025_dashboard_corrected_v01.csv.gz"
DEFAULT_OUTPUT = ROOT / "outputs" / "evaluation_v2"
MODELS = ("risk_score_v04", "risk_score_v05")
TARGETS = (
    "fda_event_any",
    "discontinuation_notice_candidate",
    "non_discontinuation_event_candidate",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DATA_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--bootstrap-replicates", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=DEFAULT_BOOTSTRAP_SEED)
    return parser.parse_args()


def load_cohort(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path, dtype={"package_ndc": "string"}, low_memory=False)
    required = {"package_ndc", *MODELS, *TARGETS, "prediction_year"}
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(f"Missing Evaluation v2 columns: {missing}")
    if len(frame) != 221_667 or set(frame["prediction_year"].unique()) != {2025}:
        raise ValueError("Evaluation v2 requires the published 2025 cohort.")
    if frame["package_ndc"].isna().any() or frame["package_ndc"].duplicated().any():
        raise ValueError("Package NDC values must be present and unique.")
    return frame


def _write_report(
    output: Path,
    frame: pd.DataFrame,
    model_metrics: pd.DataFrame,
    budget_metrics: pd.DataFrame,
    product_metrics: pd.DataFrame,
    random_metrics: pd.DataFrame,
    bootstrap_metrics: pd.DataFrame,
    missed_events: pd.DataFrame,
    heuristic_columns: list[str],
) -> None:
    top500 = budget_metrics[budget_metrics["review_budget"].eq(500)]
    top500 = top500.set_index("model")
    product_count = int(frame["_product_ndc"].nunique())
    unknown_packages = int(frame["_product_ndc"].isna().sum())
    flagged_products = int(
        frame.loc[frame["fda_event_any"].eq(1), "_product_ndc"].nunique()
    )
    lines = [
        "# PharmaOpt Evaluation v2 research report",
        "",
        "Generated by `scripts/evaluate_pharmaopt_v2.py` from the unchanged "
        "published 2025 cohort.",
        "",
        "## Scope and reproducibility",
        "",
        f"- Rows: **{len(frame):,}**; prediction year: **2025**.",
        f"- FDA-linked event flags: **{int(frame['fda_event_any'].sum())}**.",
        f"- Derived product groups: **{product_count:,}**; groups with flags: "
        f"**{flagged_products}**.",
        f"- Packages without a valid three-segment product derivation: "
        f"**{unknown_packages}**; excluded from product-level aggregates.",
        "- Product NDC is derived from the first two segments of the "
        "three-segment labeler-product-package NDC. It is a documented "
        "fallback for this published artifact, not a replacement for FDA "
        "`product_id`.",
        "- Ranking is descending score with ascending `package_ndc` tie-break.",
        "- The event labels are preserved exactly; they are not verified "
        "future shortages.",
        "",
        "## Package-level comparison",
        "",
        "| Model | Average precision | ROC-AUC | Capture @500 | Precision @500 | Recall @500 |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for model in MODELS:
        metrics = model_metrics.set_index("model").loc[model]
        row = top500.loc[model]
        lines.append(
            f"| {model} | {metrics['average_precision']:.9f} | "
            f"{metrics['roc_auc']:.6f} | {int(row['captured'])}/96 | "
            f"{row['precision']:.2%} | {row['recall']:.2%} |"
        )
    lines.extend(
        [
            "",
            "### Budget table",
            "",
            "| K | v0.4 captured | v0.4 precision | v0.4 recall | "
            "v0.5 captured | v0.5 precision | v0.5 recall | Random expected |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for budget in DEFAULT_REVIEW_BUDGETS:
        rows = budget_metrics[budget_metrics["review_budget"].eq(budget)].set_index(
            "model"
        )
        lines.append(
            f"| {budget:,} | {int(rows.loc['risk_score_v04', 'captured'])} | "
            f"{rows.loc['risk_score_v04', 'precision']:.2%} | "
            f"{rows.loc['risk_score_v04', 'recall']:.2%} | "
            f"{int(rows.loc['risk_score_v05', 'captured'])} | "
            f"{rows.loc['risk_score_v05', 'precision']:.2%} | "
            f"{rows.loc['risk_score_v05', 'recall']:.2%} | "
            f"{rows.loc['risk_score_v04', 'random_expected']:.3f} |"
        )
    lines.extend(
        [
            "",
            "## Product-level analysis",
            "",
            "Product ranking aggregates each product to its maximum package "
            "score and any event label. K is therefore a product review "
            "budget, not a package budget; the CSV includes both reviewed "
            "products and the packages represented by those products.",
            "",
            "| Model | K products | Packages represented | Flagged packages | "
            "Flagged products |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for model in MODELS:
        row = product_metrics[
            (product_metrics["model"].eq(model))
            & (product_metrics["review_budget"].eq(500))
        ].iloc[0]
        lines.append(
            f"| {model} | {int(row['reviewed_products'])} | "
            f"{int(row['reviewed_packages'])} | "
            f"{int(row['captured_flagged_packages'])} | "
            f"{int(row['captured_unique_flagged_products'])} |"
        )
    lines.extend(
        [
            "",
            "The 96 package flags map to 83 derived products. Repeated package "
            "flags within a product mean package Precision@K and product "
            "Precision@K answer different review questions.",
            "",
            "## Seeded random and heuristic baselines",
            "",
            "The seeded random baseline is one reproducible permutation using "
            "the configured seed. It is a realized draw, while "
            "`random_expected` remains the prevalence expectation.",
            "",
            "| K | Random captured | Random precision | Random recall |",
            "|---:|---:|---:|---:|",
        ]
    )
    for _, row in random_metrics.iterrows():
        lines.append(
            f"| {int(row['review_budget']):,} | {int(row['captured'])} | "
            f"{row['precision']:.2%} | {row['recall']:.2%} |"
        )
    if heuristic_columns:
        lines.extend(
            [
                "",
                "The following pre-period heuristic columns were available and "
                "evaluated: " + ", ".join(heuristic_columns) + ".",
            ]
        )
    else:
        lines.extend(
            [
                "",
                "No pre-period shortage, recall, utilization, or demand "
                "feature is present in the published dashboard artifact. "
                "Therefore no invented heuristic score is reported. The next "
                "rebuild should add named pre-period baselines from frozen "
                "source snapshots.",
            ]
        )
    lines.extend(
        [
            "",
            "## Product-cluster uncertainty",
            "",
            f"Bootstrap seed: `{int(bootstrap_metrics['seed'].iloc[0])}`; "
            f"replicates per metric: `{int(bootstrap_metrics['replicates'].iloc[0])}`.",
            "These intervals apply to the package-level ranking metrics. "
            "Products, rather than packages, are resampled as clusters so "
            "sibling packages are not treated as independent observations. "
            "The observed package order is held fixed while cluster "
            "multiplicities are resampled; this is not a refit or prospective "
            "validation.",
            "",
            "| Model | Recall@500 median | 95% interval | AP median | 95% interval |",
            "|---|---:|---:|---:|---:|",
        ]
    )
    for model in MODELS:
        recall = bootstrap_metrics[
            (bootstrap_metrics["model"].eq(model))
            & (bootstrap_metrics["metric"].eq("recall"))
            & (bootstrap_metrics["review_budget"].eq(500))
        ].iloc[0]
        average_precision = bootstrap_metrics[
            (bootstrap_metrics["model"].eq(model))
            & (bootstrap_metrics["metric"].eq("average_precision"))
        ].iloc[0]
        lines.append(
            f"| {model} | {recall['estimate']:.2%} | "
            f"{recall['lower_95']:.2%}-{recall['upper_95']:.2%} | "
            f"{average_precision['estimate']:.6f} | "
            f"{average_precision['lower_95']:.6f}-"
            f"{average_precision['upper_95']:.6f} |"
        )
    lines.extend(
        [
            "",
            "The one malformed package identifier is retained in package-level "
            "ranking and bootstrap calculations as an `__unknown_product__` "
            "singleton cluster, but is excluded from product-level aggregates.",
            "",
            "## v0.4 missed-event analysis",
            "",
            f"At K=500, v0.4 misses **{len(missed_events)}** of "
            f"{int(frame['fda_event_any'].sum())} event flags. The CSV lists "
            "each missed package, both model ranks/scores, event type, and "
            "derived product. Differences are descriptive; causes are not "
            "identified without feature-level historical records.",
            "",
            "## Limitations and next experiment",
            "",
            "- Product NDC derivation is a structural approximation because "
            "the dashboard file omits FDA `product_id`.",
            "- The published cohort has no pre-period feature columns, so "
            "heuristic baseline performance cannot be estimated from this "
            "artifact alone.",
            "- The bootstrap holds observed ranks fixed and estimates cluster "
            "sampling uncertainty; it does not remove development-set "
            "inspection or temporal-source risks.",
            "- The next phase should use frozen source snapshots to add "
            "pre-period baselines and exact FDA product mappings, then "
            "evaluate a genuinely untouched temporal period.",
        ]
    )
    (output / "evaluation_v2_report.md").write_text("\n".join(lines) + "\n")


def run(args: argparse.Namespace) -> None:
    frame = load_cohort(args.data)
    frame["_product_ndc"] = derive_product_ndc(
        frame["package_ndc"], strict=False
    )
    args.output.mkdir(parents=True, exist_ok=True)

    model_rows = []
    budget_frames = []
    product_frames = []
    random_frames = []
    bootstrap_frames = []
    heuristic_columns = [
        column
        for column in (
            "prior_shortage_count",
            "prior_recall_count",
            "prior_utilization",
            "cms_total_claims",
        )
        if column in frame.columns
    ]
    heuristic_rows = []
    for target in TARGETS:
        model_metrics, budgets = compare_rankings(
            frame, MODELS, target, DEFAULT_REVIEW_BUDGETS
        )
        model_metrics["target"] = target
        budgets["target"] = target
        model_rows.append(model_metrics)
        budget_frames.append(budgets)
        if target == "fda_event_any":
            random_frames.append(
                seeded_random_review(frame, target, DEFAULT_REVIEW_BUDGETS, args.seed)
            )
            if heuristic_columns:
                heuristic_metrics, heuristic_budget = compare_rankings(
                    frame,
                    heuristic_columns,
                    target,
                    DEFAULT_REVIEW_BUDGETS,
                )
                heuristic_metrics["baseline"] = "pre_period_heuristic"
                heuristic_budget["baseline"] = "pre_period_heuristic"
                heuristic_rows.append((heuristic_metrics, heuristic_budget))
            for model in MODELS:
                _, product_budget = evaluate_product_ranking(
                    frame, model, target, DEFAULT_REVIEW_BUDGETS
                )
                product_budget["model"] = model
                product_budget["target"] = target
                product_frames.append(product_budget)
                bootstrap = cluster_bootstrap_ranking(
                    frame,
                    model,
                    target,
                    DEFAULT_REVIEW_BUDGETS,
                    args.bootstrap_replicates,
                    args.seed,
                )
                bootstrap["model"] = model
                bootstrap["target"] = target
                bootstrap_frames.append(bootstrap)

    ranked = {}
    for model in MODELS:
        ordered = frame.sort_values(
            [model, "package_ndc"], ascending=[False, True], kind="mergesort"
        ).reset_index(drop=True)
        ordered[f"{model}_rank"] = range(1, len(ordered) + 1)
        ranked[model] = ordered
    missed = ranked["risk_score_v04"].iloc[500:].loc[
        lambda values: values["fda_event_any"].eq(1)
    ].copy()
    missed = missed[
        [
            "package_ndc",
            "_product_ndc",
            "generic_name",
            "brand_name",
            "labeler_name",
            "fda_event_any",
            "non_discontinuation_event_candidate",
            "discontinuation_notice_candidate",
            "risk_score_v04",
            "risk_score_v04_rank",
        ]
    ].merge(
        ranked["risk_score_v05"][
            ["package_ndc", "risk_score_v05", "risk_score_v05_rank"]
        ],
        on="package_ndc",
        how="left",
        validate="one_to_one",
    ).sort_values("risk_score_v04_rank")

    model_metrics = pd.concat(model_rows, ignore_index=True)
    budget_metrics = pd.concat(budget_frames, ignore_index=True)
    product_metrics = pd.concat(product_frames, ignore_index=True)
    random_metrics = pd.concat(random_frames, ignore_index=True)
    bootstrap_metrics = pd.concat(bootstrap_frames, ignore_index=True)
    if heuristic_rows:
        heuristic_metrics = pd.concat(
            [row[0] for row in heuristic_rows], ignore_index=True
        )
        heuristic_budget = pd.concat(
            [row[1] for row in heuristic_rows], ignore_index=True
        )
    else:
        heuristic_metrics = pd.DataFrame()
        heuristic_budget = pd.DataFrame()
    model_metrics.to_csv(args.output / "model_metrics.csv", index=False)
    budget_metrics.to_csv(args.output / "budget_metrics.csv", index=False)
    product_metrics.to_csv(args.output / "product_metrics.csv", index=False)
    random_metrics.to_csv(args.output / "random_baseline.csv", index=False)
    if heuristic_rows:
        heuristic_metrics.to_csv(
            args.output / "heuristic_baselines.csv", index=False
        )
        heuristic_budget.to_csv(
            args.output / "heuristic_baseline_budgets.csv", index=False
        )
    else:
        for filename in (
            "heuristic_baselines.csv",
            "heuristic_baseline_budgets.csv",
        ):
            stale_file = args.output / filename
            if stale_file.exists():
                stale_file.unlink()
    bootstrap_metrics.to_csv(args.output / "cluster_bootstrap.csv", index=False)
    missed.to_csv(args.output / "v04_missed_events.csv", index=False)
    _write_report(
        args.output,
        frame,
        model_metrics[model_metrics["target"].eq("fda_event_any")],
        budget_metrics[budget_metrics["target"].eq("fda_event_any")],
        product_metrics,
        random_metrics,
        bootstrap_metrics,
        missed,
        heuristic_columns,
    )
    print(f"Wrote Evaluation v2 artifacts to {args.output}")


if __name__ == "__main__":
    run(parse_args())
